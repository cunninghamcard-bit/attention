// Package buildcmd is `attention build`, xcaddy's idea for attention (RFC
// 0001 §5.11): Go loads no code at run time, so a third party's UI plugin
// joins by building attention again with it. The build is a main package
// of its own, in a temporary module, that imports attention's app and each
// plugin module and passes its Plugin definition to app.Main.
//
//	attention build --with github.com/you/hello-ui=./hello-ui -o ./attention-hello
package buildcmd

import (
	"bufio"
	"errors"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strconv"
	"strings"
)

// module is attention's.
const module = "github.com/cunninghamcard-bit/attention/native"

// with is a --with: a module path, optionally at a version or, after "=",
// a local folder that replaces it.
type with struct{ path, version, dir string }

func parseWith(s string) (with, error) {
	var w with
	s, w.dir, _ = strings.Cut(s, "=")
	w.path, w.version, _ = strings.Cut(s, "@")
	if w.path == "" {
		return w, fmt.Errorf("--with %q names no module", s)
	}
	if w.dir != "" {
		abs, err := filepath.Abs(w.dir)
		if err != nil {
			return w, err
		}
		w.dir = abs
	}
	return w, nil
}

type withs []with

func (ws *withs) String() string { return "" }
func (ws *withs) Set(s string) error {
	w, err := parseWith(s)
	if err == nil {
		*ws = append(*ws, w)
	}
	return err
}

// Run is `attention build [--with <module>[@version][=dir]]... [-o file]
// [--source dir]`.
func Run(args []string) int {
	fs := flag.NewFlagSet("attention build", flag.ContinueOnError)
	var ws withs
	fs.Var(&ws, "with", "a plugin module: path[@version][=local folder] (repeatable)")
	out := fs.String("o", "attention", "the binary to write")
	source := fs.String("source", "", "attention's native/ folder (default: $ATTENTION_SOURCE, else found from this binary)")
	keep := fs.Bool("keep", false, "keep the generated module and print where")
	if err := fs.Parse(args); err != nil {
		return 2
	}
	if err := build(ws, *out, *source, *keep); err != nil {
		fmt.Fprintln(os.Stderr, "attention build:", err)
		return 1
	}
	return 0
}

func build(ws withs, out, source string, keep bool) error {
	src, err := sourceDir(source)
	if err != nil {
		return err
	}
	out, err = filepath.Abs(out)
	if err != nil {
		return err
	}
	dir, err := os.MkdirTemp("", "attention-build-")
	if err != nil {
		return err
	}
	if keep {
		fmt.Fprintln(os.Stderr, "attention build: module in", dir)
	} else {
		defer os.RemoveAll(dir)
	}
	if err := os.WriteFile(filepath.Join(dir, "main.go"), []byte(mainFile(ws)), 0o644); err != nil {
		return err
	}
	gomod, err := goMod(src, ws)
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(dir, "go.mod"), []byte(gomod), 0o644); err != nil {
		return err
	}
	// attention's go.sum covers its own dependencies; tidy adds the
	// plugins'.
	if sum, err := os.ReadFile(filepath.Join(src, "go.sum")); err == nil {
		_ = os.WriteFile(filepath.Join(dir, "go.sum"), sum, 0o644)
	}
	if err := gocmd(dir, "mod", "tidy"); err != nil {
		return err
	}
	if err := gocmd(dir, "build", "-o", out, "."); err != nil {
		return err
	}
	fmt.Println("Built: " + out)
	return nil
}

// mainFile is the custom attention's main: attention's, with each plugin
// module's Plugin passed to app.Main.
func mainFile(ws withs) string {
	var b strings.Builder
	b.WriteString("// Code generated by attention build. DO NOT EDIT.\n\npackage main\n\nimport (\n")
	b.WriteString("\t\"" + module + "/app\"\n")
	var args []string
	for i, w := range ws {
		alias := "p" + strconv.Itoa(i)
		b.WriteString("\t" + alias + " \"" + w.path + "\"\n")
		args = append(args, alias+".Plugin")
	}
	b.WriteString(")\n\nfunc main() { app.Main(" + strings.Join(args, ", ") + ") }\n")
	return b.String()
}

// goMod requires attention from its source folder, with its own replaces,
// and each plugin module, from its folder when given one.
func goMod(src string, ws withs) (string, error) {
	goVersion, replaces, err := readGoMod(filepath.Join(src, "go.mod"))
	if err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString("module attention-custom\n\ngo " + goVersion + "\n\n")
	b.WriteString("require " + module + " v0.0.0\n")
	b.WriteString("replace " + module + " => " + src + "\n")
	for _, r := range replaces {
		b.WriteString("replace " + r + "\n")
	}
	for _, w := range ws {
		version := w.version
		if w.dir != "" || version == "" {
			version = "v0.0.0"
		}
		b.WriteString("require " + w.path + " " + version + "\n")
		if w.dir != "" {
			b.WriteString("replace " + w.path + " => " + w.dir + "\n")
		}
	}
	return b.String(), nil
}

// readGoMod is a go.mod's go version and replace directives, their local
// folders made absolute.
func readGoMod(path string) (goVersion string, replaces []string, err error) {
	f, err := os.Open(path)
	if err != nil {
		return "", nil, err
	}
	defer f.Close()
	sc := bufio.NewScanner(f)
	inBlock := false
	add := func(line string) {
		from, to, ok := strings.Cut(line, "=>")
		if !ok {
			return
		}
		to = strings.TrimSpace(to)
		if strings.HasPrefix(to, ".") {
			to = filepath.Join(filepath.Dir(path), to)
		}
		replaces = append(replaces, strings.TrimSpace(from)+" => "+to)
	}
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		switch {
		case strings.HasPrefix(line, "go "):
			goVersion = strings.TrimSpace(strings.TrimPrefix(line, "go "))
		case line == "replace (":
			inBlock = true
		case inBlock && line == ")":
			inBlock = false
		case inBlock:
			add(line)
		case strings.HasPrefix(line, "replace "):
			add(strings.TrimPrefix(line, "replace "))
		}
	}
	if goVersion == "" {
		return "", nil, errors.New(path + " names no go version")
	}
	return goVersion, replaces, sc.Err()
}

// sourceDir is attention's native/ folder: the one given, $ATTENTION_SOURCE,
// or the first folder above this binary whose go.mod is attention's.
func sourceDir(given string) (string, error) {
	if given == "" {
		given = os.Getenv("ATTENTION_SOURCE")
	}
	if given != "" {
		return filepath.Abs(given)
	}
	self, err := os.Executable()
	if err != nil {
		return "", err
	}
	if resolved, err := filepath.EvalSymlinks(self); err == nil {
		self = resolved
	}
	for dir := filepath.Dir(self); ; dir = filepath.Dir(dir) {
		if data, err := os.ReadFile(filepath.Join(dir, "go.mod")); err == nil && strings.Contains(string(data), "module "+module+"\n") {
			return dir, nil
		}
		if parent := filepath.Dir(dir); parent == dir {
			return "", errors.New("attention's source not found: pass --source or set ATTENTION_SOURCE to its native/ folder")
		}
	}
}

func gocmd(dir string, args ...string) error {
	cmd := exec.Command("go", args...)
	cmd.Dir = dir
	cmd.Stdout, cmd.Stderr = os.Stderr, os.Stderr
	cmd.Env = append(os.Environ(), "GOWORK=off")
	if err := cmd.Run(); err != nil {
		return fmt.Errorf("go %s: %w", strings.Join(args, " "), err)
	}
	return nil
}
